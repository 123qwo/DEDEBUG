param([string]$GameDir = $env:DICEOMANCER_GAME_DIR)
$ErrorActionPreference = 'Stop'
if ([string]::IsNullOrWhiteSpace($GameDir)) { throw 'Pass -GameDir or set DICEOMANCER_GAME_DIR to your game directory.' }
Add-Type -Path (Join-Path $GameDir 'BepInEx\core\Mono.Cecil.dll')
$assembly = [Mono.Cecil.AssemblyDefinition]::ReadAssembly((Join-Path $GameDir 'Diceomancer_Data\Managed\Assembly-CSharp.dll'))
try {
    function Expand-InputTypes($Types) { foreach ($type in $Types) { $type; Expand-InputTypes $type.NestedTypes } }
    $supported = @('GetKey','GetKeyDown','GetKeyUp','GetMouseButton','GetMouseButtonDown','GetMouseButtonUp','GetAxis','GetAxisRaw',
        'GetButton','GetButtonDown','GetButtonUp','GetTouch','get_touchCount','get_mouseScrollDelta','get_mousePosition','get_anyKey','get_anyKeyDown','get_inputString')
    $targets = @(foreach ($type in Expand-InputTypes $assembly.MainModule.Types) {
        foreach ($method in $type.Methods | Where-Object HasBody) {
            $reads = @($method.Body.Instructions | ForEach-Object { $_.Operand } | Where-Object {
                $_ -is [Mono.Cecil.MethodReference] -and $_.DeclaringType.FullName -eq 'UnityEngine.Input' -and -not $_.Name.StartsWith('set_')
            })
            foreach ($read in $reads) { if ($read.Name -notin $supported) { throw "Unsupported game input read: $($read.FullName)" } }
            if ($reads.Count -gt 0) { [pscustomobject]@{Token=$method.MetadataToken.ToInt32(); Method=$method.FullName; Reads=@($reads.FullName)} }
        }
    })
    if ($targets.Count -eq 0) { throw 'No game input read targets found.' }
    $source = "// Generated by Generate-InputManifest.ps1. Rebuild for a new game assembly.`nnamespace DEDEBUG;`ninternal static class GameInputManifest`n{`n" +
        "    internal const string ModuleId = `"$($assembly.MainModule.Mvid)`";`n" +
        "    internal static readonly int[] Tokens = { " + (($targets.Token | Sort-Object -Unique) -join ', ') + " };`n}`n"
    $generated = Join-Path $PSScriptRoot '.build\generated'
    New-Item -ItemType Directory -Path $generated -Force | Out-Null
    $path = Join-Path $generated 'GameInputManifest.cs'
    if (-not (Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path) -ne $source) {
        [IO.File]::WriteAllText($path, $source, [Text.UTF8Encoding]::new($false))
    }
    New-Item -ItemType Directory -Path (Join-Path $PSScriptRoot '.build\diagnostics') -Force | Out-Null
    [ordered]@{ModuleId=$assembly.MainModule.Mvid.ToString(); Targets=$targets} | ConvertTo-Json -Depth 6 |
        Set-Content -LiteralPath (Join-Path $PSScriptRoot '.build\diagnostics\InputManifest.json') -Encoding utf8
    "Generated input isolation manifest: $($targets.Count) methods."
} finally { $assembly.Dispose() }
